//! winit physical key → AT set-1 scancode (extended keys as 0xE0xx), the
//! form `qemu_embed_atset1_to_qcode` expects.

use winit::keyboard::KeyCode as K;

pub fn atset1(code: K) -> Option<u32> {
    Some(match code {
        K::Escape => 0x01,
        K::Digit1 => 0x02,
        K::Digit2 => 0x03,
        K::Digit3 => 0x04,
        K::Digit4 => 0x05,
        K::Digit5 => 0x06,
        K::Digit6 => 0x07,
        K::Digit7 => 0x08,
        K::Digit8 => 0x09,
        K::Digit9 => 0x0A,
        K::Digit0 => 0x0B,
        K::Minus => 0x0C,
        K::Equal => 0x0D,
        K::Backspace => 0x0E,
        K::Tab => 0x0F,
        K::KeyQ => 0x10,
        K::KeyW => 0x11,
        K::KeyE => 0x12,
        K::KeyR => 0x13,
        K::KeyT => 0x14,
        K::KeyY => 0x15,
        K::KeyU => 0x16,
        K::KeyI => 0x17,
        K::KeyO => 0x18,
        K::KeyP => 0x19,
        K::BracketLeft => 0x1A,
        K::BracketRight => 0x1B,
        K::Enter => 0x1C,
        K::ControlLeft => 0x1D,
        K::KeyA => 0x1E,
        K::KeyS => 0x1F,
        K::KeyD => 0x20,
        K::KeyF => 0x21,
        K::KeyG => 0x22,
        K::KeyH => 0x23,
        K::KeyJ => 0x24,
        K::KeyK => 0x25,
        K::KeyL => 0x26,
        K::Semicolon => 0x27,
        K::Quote => 0x28,
        K::Backquote => 0x29,
        K::ShiftLeft => 0x2A,
        K::Backslash => 0x2B,
        K::KeyZ => 0x2C,
        K::KeyX => 0x2D,
        K::KeyC => 0x2E,
        K::KeyV => 0x2F,
        K::KeyB => 0x30,
        K::KeyN => 0x31,
        K::KeyM => 0x32,
        K::Comma => 0x33,
        K::Period => 0x34,
        K::Slash => 0x35,
        K::ShiftRight => 0x36,
        K::NumpadMultiply => 0x37,
        K::AltLeft => 0x38,
        K::Space => 0x39,
        K::CapsLock => 0x3A,
        K::F1 => 0x3B,
        K::F2 => 0x3C,
        K::F3 => 0x3D,
        K::F4 => 0x3E,
        K::F5 => 0x3F,
        K::F6 => 0x40,
        K::F7 => 0x41,
        K::F8 => 0x42,
        K::F9 => 0x43,
        K::F10 => 0x44,
        K::NumLock => 0x45,
        K::ScrollLock => 0x46,
        K::Numpad7 => 0x47,
        K::Numpad8 => 0x48,
        K::Numpad9 => 0x49,
        K::NumpadSubtract => 0x4A,
        K::Numpad4 => 0x4B,
        K::Numpad5 => 0x4C,
        K::Numpad6 => 0x4D,
        K::NumpadAdd => 0x4E,
        K::Numpad1 => 0x4F,
        K::Numpad2 => 0x50,
        K::Numpad3 => 0x51,
        K::Numpad0 => 0x52,
        K::NumpadDecimal => 0x53,
        K::IntlBackslash => 0x56,
        K::F11 => 0x57,
        K::F12 => 0x58,
        // extended
        K::NumpadEnter => 0xE01C,
        K::ControlRight => 0xE01D,
        K::NumpadDivide => 0xE035,
        K::PrintScreen => 0xE037,
        K::AltRight => 0xE038,
        K::Home => 0xE047,
        K::ArrowUp => 0xE048,
        K::PageUp => 0xE049,
        K::ArrowLeft => 0xE04B,
        K::ArrowRight => 0xE04D,
        K::End => 0xE04F,
        K::ArrowDown => 0xE050,
        K::PageDown => 0xE051,
        K::Insert => 0xE052,
        K::Delete => 0xE053,
        K::SuperLeft => 0xE05B,
        K::SuperRight => 0xE05C,
        K::ContextMenu => 0xE05D,
        _ => return None,
    })
}
